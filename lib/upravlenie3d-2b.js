/* Дополнительные 3D-модели: «Теория управления. Лекция 2». Помощники — lib/upravlenie3d-common.js. */
(function () {
  'use strict';
  if (!window.TU3) return;
  var U = window.TU3, reg = U.reg;

  /* ---------- 1. Гилбрет: 18 движений → 5 ---------- */
  reg('tu2-gilbreth', {
    title: 'Гилбрет и каменщик: 18 движений → 5', lead: 'Светящийся шарик — рука каменщика. Оранжевая линия — её путь за один кирпич. Сравни старый способ и способ Гилбрета.',
    radius: 16, phi: 1.05, targetY: 1.5,
    build: function (c) {
      var T = c.THREE, S = c.state = { mode: 0, laid: 0 };
      for (var r = 0; r < 4; r++) for (var k = 0; k < 6; k++) c.box3(1, 0.45, 0.5, '#b5583e', [-3 + k * 1.05 + (r % 2) * 0.5, 0.25 + r * 0.48, 0], 'Стена. Чем меньше лишних движений, тем быстрее она растёт.');
      c.box3(2, 0.6, 1.2, '#8a6a4a', [4.5, 0.3, 2], '<b>Подставка с кирпичами</b> на уровне пояса — изобретение Гилбрета: не надо нагибаться к земле.');
      c.pile = c.box3(1.6, 0.5, 1.2, '#8a6a4a', [-5, 0.25, 3], 'Старый способ: кирпичи свалены на землю — каменщик каждый раз нагибается.');
      var oldPts = [], newPts = [];
      for (var i = 0; i <= 18; i++) { var a = i / 18; oldPts.push([-5 + Math.sin(i * 1.7) * 2 + a * 6, 0.6 + Math.abs(Math.sin(i * 2.3)) * 2.4, 3 - a * 2.6 + Math.cos(i * 1.3)]); }
      newPts = [[4.5, 1, 2], [3, 1.8, 1.4], [1.5, 2.3, 0.8], [0.5, 2.2, 0.4], [0, 2.1, 0.3]];
      c.oldT = U.tube(c, oldPts, '#ff8f66', 0.05, false, 'Старый путь руки: <b>18 движений</b> на один кирпич.');
      c.newT = U.tube(c, newPts, '#4cc38a', 0.07, false, 'Путь Гилбрета: <b>около 5 движений</b>.');
      var hand = U.glow(c, '#ffffff', 0.25);
      c.cnt = c.label('18 движений', [0, 4.6, 0], 0.6, '#ff8f66');
      c.onFrame(function (t) {
        c.oldT.visible = !S.mode; c.newT.visible = !!S.mode; c.pile.visible = !S.mode;
        var cv = S.mode ? c.newT.userData.curve : c.oldT.userData.curve, sp = S.mode ? 0.5 : 0.17;
        hand.position.copy(cv.getPointAt(U.W(t * sp)));
      });
    },
    chips: [
      { t: 'По старинке', small: '18 движений', on: function (c) { c.state.mode = 0; c.say('Кирпичи на земле, рука мечется: <b>18 движений</b> на кирпич.'); } },
      { t: 'По Гилбрету', small: '≈5 движений', on: function (c) { c.state.mode = 1; c.say('Подставка на уровне пояса, кирпичи разложены лицом вверх: <b>около 5 движений</b>, выработка выросла почти <b>втрое</b>. Элементарные движения — «терблиги».'); } }
    ]
  });

  /* ---------- 2. Идеальная бюрократия Вебера ---------- */
  reg('tu2-weber', {
    title: 'Идеальная бюрократия Вебера', lead: 'Здание из этажей-уровней. Нажми на элементы: правила-папки, иерархия, отбор по квалификации, безличность.',
    radius: 18, phi: 1.1, targetY: 3,
    build: function (c) {
      var T = c.THREE;
      var F = [[6, 1.2, '#5b6a99'], [4.8, 1.2, '#6c7cb0'], [3.6, 1.2, '#7d8dc4'], [2.4, 1.2, '#8f9fd8']];
      var y = 0;
      F.forEach(function (f, i) { c.box3(f[0], f[1], 3, f[2], [0, y + f[1] / 2, 0], '<b>Чёткая иерархия</b>: каждый уровень подчиняется вышестоящему. Этаж ' + (i + 1) + '.'); y += f[1]; });
      c.mesh(new T.ConeGeometry(1.8, 1.2, 4), '#f0c36b', 'Вершина иерархии.').position.set(0, y + 0.6, 0);
      for (var k = 0; k < 5; k++) { c.box3(0.6, 0.8, 0.12, '#f3e3b0', [-2.4 + k * 0.4, 0.4, 1.7], '<b>Письменные правила</b>: всё решается по инструкциям, а не по прихоти начальника.'); }
      for (var j = 0; j < 4; j++) for (var m = 0; m < 3; m++) c.box3(0.5, 0.5, 0.05, '#ffe9a8', [-1.6 + m * 1.6 - (j * 0.3), 0.6 + j * 1.2, 1.53 + 0.01], j ? 'Отдел: <b>разделение функций</b>.' : 'Отдел: <b>разделение функций</b>.').scale.set(1 - j * 0.15, 1, 1);
      var dip = c.box3(0.8, 0.6, 0.06, '#4cc38a', [3.8, 1.2, 1], '<b>Отбор по квалификации</b>: на должность берут по знаниям и экзаменам, а не по знакомству.');
      dip.rotation.y = -0.4;
      var mask = c.mesh(new T.SphereGeometry(0.5, 16, 12), '#e8e8e8', '<b>Безличность</b>: правила одинаковы для всех, решение не зависит от симпатий.'); mask.position.set(-3.8, 1.2, 1);
      c.label('правила', [-1.6, 1.3, 2.4], 0.45, '#f3e3b0'); c.label('квалификация', [3.8, 2.1, 1], 0.45, '#4cc38a'); c.label('безличность', [-3.8, 2.1, 1], 0.45);
    },
    hint: 'У Вебера «бюрократия» — не ругательство, а модель рационального управления.'
  });

  /* ---------- 3. Херцберг: гигиена и мотиваторы ---------- */
  reg('tu2-herzberg', {
    title: 'Двухфакторная теория Херцберга', lead: 'Шарик — настроение работника. Слева «недовольство», справа «увлечённость». Гигиенические факторы доводят шарик только до нуля. Дальше двигают лишь мотиваторы.',
    radius: 18, phi: 1.0, targetY: 1,
    build: function (c) {
      var T = c.THREE, S = c.state = { h: 0, m: 0, x: -5 };
      c.box3(12, 0.3, 1.4, '#3a4270', [0, 0, 0], 'Шкала настроения.');
      c.box3(6, 0.32, 1.42, '#ef6b5b', [-3, 0.01, 0], 'Зона недовольства.').material.opacity = 1;
      c.box3(6, 0.32, 1.42, '#4cc38a', [3, 0.01, 0], 'Зона увлечённости.');
      c.box3(0.15, 1.6, 1.6, '#ffffff', [0, 0.8, 0], '<b>Ноль</b>: недовольства нет, но и увлечённости нет.');
      c.label('недовольство', [-4, 1.5, 0], 0.5, '#ef6b5b'); c.label('увлечённость', [4, 1.5, 0], 0.5, '#4cc38a'); c.label('0', [0, 2.3, 0], 0.5);
      var ball = c.mesh(new T.SphereGeometry(0.6, 24, 16), '#f0c36b', 'Настроение работника.'); ball.position.set(-5, 0.75, 0);
      c.hyg = []; c.mot = [];
      [['зарплата', -5], ['условия', -3.2], ['надёжность', -1.4]].forEach(function (h) { var m = c.box3(1, 0.6, 0.6, '#7aa2ff', [h[1], 0.5, -2], '<b>Гигиенический фактор: ' + h[0] + '</b>. Убирает недовольство, но не зажигает.'); m.visible = false; c.hyg.push(m); c.label(h[0], [h[1], 1.3 + (h[1] === -3.2 ? 0.7 : 0), -2], 0.32, '#7aa2ff'); });
      [['признание', 1.4], ['рост', 3.2], ['интересная\nработа', 5]].forEach(function (h) { var m = c.box3(1, 0.6, 0.6, '#c9b6f0', [h[1], 0.5, -2], '<b>Мотиватор: ' + h[0] + '</b>. Действительно мотивирует.'); m.visible = false; c.mot.push(m); c.label(h[0], [h[1], 1.3 + (h[1] === 3.2 ? 0.7 : 0), -2], 0.32, '#c9b6f0'); });
      c.onFrame(function () { var goal = -5 + S.h * 5 + (S.h ? S.m * 5 : S.m * 1.2); S.x += (goal - S.x) * 0.05; ball.position.x = S.x; ball.rotation.z = -S.x; c.hyg.forEach(function (m) { m.visible = !!S.h; }); c.mot.forEach(function (m) { m.visible = !!S.m; }); });
    },
    chips: [
      { t: 'Ничего', small: 'исходно', on: function (c) { c.state.h = 0; c.state.m = 0; c.say('Низкая зарплата и плохие условия — работник недоволен.'); } },
      { t: '+ Гигиена', small: 'зарплата, условия', on: function (c) { c.state.h = 1; c.state.m = 0; c.say('Подняли зарплату и улучшили условия — недовольство ушло, но шарик застрял на <b>нуле</b>. Деньги сами по себе не зажигают.'); } },
      { t: '+ Мотиваторы', small: 'признание, рост', on: function (c) { c.state.h = 1; c.state.m = 1; c.say('Добавили признание, рост и интересную работу — шарик ушёл в <b>увлечённость</b>.'); } },
      { t: 'Только мотиваторы', on: function (c) { c.state.h = 0; c.state.m = 1; c.say('Похвала при нищенской зарплате почти не помогает: сначала закрой «гигиену».'); } }
    ]
  });

  /* ---------- 4. Теория очередей ---------- */
  reg('tu2-queue', {
    title: 'Теория очередей: сколько касс открыть', lead: 'Покупатели приходят непрерывно. Выбери число касс: мало — очередь растёт, много — кассиры скучают. Количественная школа ищет оптимум расчётом.',
    radius: 12, phi: 0.95, targetY: 0.3, theta: 0.2,
    build: function (c) {
      var T = c.THREE, S = c.state = { k: 2, q: [0, 0, 0, 0, 0], acc: 0, last: 0 };
      c.box3(13, 0.1, 9, '#3a4270', [0, -0.05, 0.5], 'Торговый зал.');
      c.desks = []; c.queues = [];
      for (var i = 0; i < 5; i++) {
        var x = -5 + i * 2.5;
        c.desks.push(c.box3(1.6, 1, 0.8, '#7aa2ff', [x, 0.5, -3], 'Касса ' + (i + 1) + '.'));
        var arr = []; for (var j = 0; j < 8; j++) { var p = c.mesh(new T.CapsuleGeometry(0.3, 0.6, 4, 8), '#f0c36b', 'Покупатель в очереди.'); p.position.set(x, 0.5, -2 + j * 0.7); p.visible = false; arr.push(p); }
        c.queues.push(arr);
      }
      c.status = null;
      c.onFrame(function (t) {
        var dt = Math.min(0.1, t - S.last); S.last = t; S.acc += dt;
        if (S.acc > 0.5) {
          S.acc = 0;
          var best = 0; for (var a = 1; a < S.k; a++) if (S.q[a] < S.q[best]) best = a;
          S.q[best] = Math.min(8, S.q[best] + (Math.random() < 0.95 ? 1 : 0));
          for (var b = 0; b < S.k; b++) if (Math.random() < 0.34 && S.q[b] > 0) S.q[b]--;
        }
        for (var i = 0; i < 5; i++) {
          if (i >= S.k) S.q[i] = 0;
          c.desks[i].material.color.set(i < S.k ? (S.q[i] ? '#7aa2ff' : '#9aa2c0') : '#2b3154');
          c.queues[i].forEach(function (p, j) { p.visible = j < S.q[i]; p.material.color.set(S.q[i] > 5 ? '#ef6b5b' : '#f0c36b'); });
        }
      });
    },
    chips: [
      { t: '2 кассы', small: 'мало', on: function (c) { c.state.k = 2; c.say('Две кассы не успевают: очереди растут и краснеют. Покупатели уходят.'); } },
      { t: '3 кассы', small: 'оптимум', on: function (c) { c.state.k = 3; c.say('Три кассы: очередь короткая, кассиры заняты. Это и ищет <b>теория очередей</b>.'); } },
      { t: '5 касс', small: 'много', on: function (c) { c.state.k = 5; c.say('Пять касс: очереди нет, но кассы часто простаивают (серые) — лишние расходы на зарплату.'); } }
    ]
  });

  /* ---------- 5. Системная динамика Форрестера ---------- */
  reg('tu2-forrester', {
    title: 'Системная динамика: петля города', lead: 'Пять узлов связаны в петлю. Шарики бегут по стрелкам. Нажми «Новые рабочие места» и проследи, как эффект сам себя гасит.',
    radius: 18, phi: 0.75, targetY: 0.5,
    build: function (c) {
      var T = c.THREE;
      var N = [['больше рабочих мест', '#4cc38a', 'Город создаёт рабочие места.'], ['больше переезжающих', '#7aa2ff', 'Люди едут туда, где есть работа.'], ['нагрузка на жильё', '#f0c36b', 'Жилья на всех не хватает.'], ['дороже жильё', '#ff8f66', 'Цены на квартиры растут.'], ['меньше переезжающих', '#ef6b5b', 'Дорогое жильё отпугивает — приток людей падает. Петля замкнулась: «очевидное» решение дало обратный эффект.']];
      var pts = [];
      c.nodes = N.map(function (n, i) {
        var a = i / 5 * Math.PI * 2, x = Math.sin(a) * 5, z = Math.cos(a) * 5;
        pts.push([x, 0.8, z]);
        var m = c.mesh(new T.SphereGeometry(0.8, 24, 16), n[1], '<b>' + n[0] + '</b>: ' + n[2]); m.position.set(x, 0.8, z);
        c.label(n[0], [x * 1.3, 2.1, z * 1.3], 0.45, n[1]); return m;
      });
      for (var i = 0; i < 5; i++) {
        var a = pts[i], b = pts[(i + 1) % 5], d = [b[0] - a[0], 0, b[2] - a[2]], L = Math.hypot(d[0], d[2]);
        U.arrow(c, [a[0] + d[0] / L, 0.8, a[2] + d[2] / L], [b[0] - d[0] / L, 0.8, b[2] - d[2] / L], '#9aa2c0', i === 3 ? 'Связь «−»: чем дороже жильё, тем <b>меньше</b> приезжих.' : 'Связь «+»: одно растёт — растёт и другое.', 0.07);
        c.label(i === 3 ? '−' : '+', [(a[0] + b[0]) / 2, 1.6, (a[2] + b[2]) / 2], 0.6, i === 3 ? '#ef6b5b' : '#4cc38a');
      }
      U.movers(c, U.curve(c, pts, true), '#ffffff', 0.08, 3, 0.18);
    },
    chips: [
      { t: 'Новые рабочие места', on: function (c) { c.pick(c.nodes[0]); c.setView(0, 0.8, 16, 0.5); } },
      { t: 'Чем кончится?', on: function (c) { c.pick(c.nodes[4]); c.setView(-1.2, 0.8, 16, 0.5); } }
    ]
  });
})();
